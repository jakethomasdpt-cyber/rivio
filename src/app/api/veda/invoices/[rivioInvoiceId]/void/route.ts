import { NextRequest, NextResponse } from 'next/server';
import Stripe from 'stripe';
import { getDatabasePool } from '@/lib/database';
import { cancellationSafetyInstalled, assertInvoiceUnpaid, assertNoRecordedPayments, expireInvoiceCheckoutSessions, InvoicePaymentConflict, withLockedInvoice } from '@/lib/invoicePaymentSafety';
import { authenticateVedaRequest, emitVedaInvoiceEvent, getIdempotentResponse, storeIdempotentResponse } from '@/lib/vedaIntegration';

export const dynamic = 'force-dynamic';

export async function POST(request: NextRequest, { params }: { params: Promise<{ rivioInvoiceId: string }> }) {
  const auth = await authenticateVedaRequest(request);
  if (!auth.ok) return auth.response;
  const { rivioInvoiceId } = await params;
  const idempotencyKey = request.headers.get('idempotency-key');
  // Do not replay confirmations generated by the previous unsafe void implementation.
  const scope = `veda.invoice.safe-void.v1.${rivioInvoiceId}`;
  const cached = await getIdempotentResponse(scope, idempotencyKey);
  if (cached) return cached;
  try {
    if (!await cancellationSafetyInstalled(getDatabasePool())) throw new InvoicePaymentConflict('Safe cancellation is not installed.');
    const stripe = new Stripe(process.env.STRIPE_SECRET_KEY!, { apiVersion: '2026-03-25.dahlia' as const });
    const responseBody = await withLockedInvoice(getDatabasePool(), rivioInvoiceId, async (client, invoice) => {
      if (!invoice.veda_organization_id || auth.body.vedaOrganizationId !== invoice.veda_organization_id
        || auth.body.vedaInvoiceId !== invoice.veda_invoice_id) {
        throw new InvoicePaymentConflict('Veda invoice identity does not match.');
      }
      assertInvoiceUnpaid(invoice);
      await assertNoRecordedPayments(client, invoice.id);
      await expireInvoiceCheckoutSessions(stripe, invoice);
      // Remote session expiration must succeed before local cancellation is committed.
      const result = await client.query(`UPDATE public.invoices SET status = 'cancelled', voided_at = COALESCE(voided_at, now())
        WHERE id = $1 AND COALESCE(paid_amount, 0) = 0 AND paid_date IS NULL
          AND status NOT IN ('paid', 'partially_paid', 'refunded') RETURNING voided_at`, [invoice.id]);
      if (!result.rows.length) throw new InvoicePaymentConflict('Invoice payment state changed.');
      if (invoice.status !== 'cancelled') await client.query(`INSERT INTO public.timeline_events
        (invoice_id,event_type,description,metadata,created_at) VALUES ($1,'cancelled','Invoice voided by Veda EMR',$2,now())`,
      [invoice.id, JSON.stringify(auth.body.metadata || {})]);
      return { rivioInvoiceId: invoice.id, invoiceNumber: invoice.invoice_number, status: 'cancelled',
        vedaOrganizationId: invoice.veda_organization_id, vedaInvoiceId: invoice.veda_invoice_id,
        voidedAt: result.rows[0].voided_at, voidSafetyVersion: 1, checkoutDisabled: true, paidAmountCents: 0 };
    });
    await emitVedaInvoiceEvent({ eventType: 'invoice.voided', invoiceId: rivioInvoiceId });
    await storeIdempotentResponse(scope, idempotencyKey, 200, responseBody);
    return NextResponse.json(responseBody);
  } catch (err) {
    if (err instanceof InvoicePaymentConflict) return NextResponse.json({ error: err.message }, { status: 409 });
    console.error('POST /api/veda/invoices/[rivioInvoiceId]/void error:', err);
    return NextResponse.json({ error: 'Invoice cancellation could not be confirmed. Retry after checking payment status.' }, { status: 500 });
  }
}
